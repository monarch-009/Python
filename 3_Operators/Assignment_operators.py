# Assignment Operators in Python
# Assignment operators are used to assign values to variables. They can also perform arithmetic operations and assign
x = 10

# Assignment operators in Python allow you to perform operations and assign the result to a variable in a single step.

x += 5     # x = x + 5 → 15
x -= 3     # x = x - 3 → 12
x *= 2     # x = x * 2 → 24
x /= 4     # x = x / 4 → 6.0
x //= 2    # x = x // 2 → 3.0
x %= 2     # x = x % 2 → 1.0
x **= 3    # x = x ** 3 → 1.0
print("Final value of x:", x)  # Output: Final value of x: 1.0