# Typecasting is the process of converting one data type to another.
# In Python, typecasting can be done using built-in functions like `int()`, `float()`, `str()`, and `bool()`.

# Example of Typecasting in Python

# Converting a string to an integer
age_str = "25"
age_int = int(age_str)
print("Age as integer:", age_int)

# Converting an integer to a float
height_int = 180
height_float = float(height_int)
print("Height as float:", height_float)

# Converting a float to a string
weight_float = 70.5
weight_str = str(weight_float)
print("Weight as string:", weight_str)

# Converting a boolean to an integer
is_student = True
is_student_int = int(is_student)
print("Is student as integer:", is_student_int)

# Converting an integer to a boolean
is_adult = 18
is_adult_bool = bool(is_adult)
print("Is adult as boolean:", is_adult_bool)

