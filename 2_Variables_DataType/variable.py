# Variable 
# A variable is a name that is used to store a value in a program.
# It acts like a container that holds data which can change during program execution.

age = 25
print(age)

# Identifier
# An identifier is the name used to identify variables, functions, classes, modules, etc.
# It must follow these rules:
# Can contain letters (A–Z, a–z), digits (0–9), and underscores (_)
# Cannot start with a digit
# Cannot be a keyword
# Are case-sensitive (e.g., Name and name are different)
student_name = "Aditya"
print(student_name)

#  Keyword
# A keyword is a reserved word in a programming language that has a special meaning.
# You cannot use keywords as variable names or identifiers. 

# if, else, for, while, def, return, True, False, class, import

if age > 18:
    print("Adult")




