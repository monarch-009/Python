# Indexing a string allows you to access individual characters using their position in the string.
# The first character is at index 0, the second at index 1, and so
# on. Negative indexing allows you to access characters from the end of the string, with -1 being the last character.
# For example, in the string "Aditya Singh":

a = "Aditya Singh"

print(a[0])  # Output: A (first character)
print(a[1])  # Output: d (second character)
print(a[7])  # Output: S (eighth character)
print(a[-1])  # Output: g (last character)
print(a[-2])  # Output: n (second last character)
print(a[-8])  # Output: A (eighth character from the end)
