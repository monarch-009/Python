# String Functions
# String functions are built-in methods that allow you to manipulate and analyze strings in Python.


a = "Aditya Singh"

# 1. String Length
print("Length of the string:", len(a))  # Output: 13

# 2. Type of String
print("Type of the string:", type(a))  # Output: <class 'str'   >

# 3. Sting Sorting
print("Sorted string:", sorted(a))  # Output: ['A', 'S', 'a', 'd', 'g', 'h', 'i', 'i', 'n', 't', 'y']

