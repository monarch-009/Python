name = "Aditya Singh"

# String Medhods
print("Upper Method: ",name.upper())  # Converts the string to uppercase
print("Lower Method: ",name.lower())  # Converts the string to lowercase
print("Title Method: ",name.title())  # Converts the first character of each word to uppercase
print("Capitalize Method: ",name.capitalize())  # Converts the first character of the string to uppercase
print("Swapcase Method: ",name.swapcase())  # Swaps the case of each character in the string
print("Count Method: ",name.count('a'))  # Counts the occurrences of 'a' in the string
print("Find Method: ",name.find('a'))  # Finds the first occurrence of 'a' in the string and returns its index
print("Index Method: ",name.index('a'))  # Finds the first occurrence of 'a' in the string and returns its index (raises an error if not found)
print("Replace Method: ",name.replace('Aditya', 'John'))  # Replaces 'Aditya' with 'John' in the string
print("Split Method: ",name.split())  # Splits the string into a list of words
print("Join Method: ",', '.join(['Aditya', 'Singh']))  # Joins the list of words with a comma and space
print("Strip Method: ",name.strip())  # Removes leading and trailing whitespace from the string
print("Startswith Method: ",name.startswith('Aditya'))  # Checks if the string starts with 'Aditya'
print("Endswith Method: ",name.endswith('Singh'))  # Checks if the string ends with 'Singh'
print("Isalpha Method: ",name.isalpha())  # Checks if the string contains only alphabetic characters
print("Isdigit Method: ",name.isdigit())  # Checks if the string contains only digits
print("Isalnum Method: ",name.isalnum())  # Checks if the string contains only alphanumeric characters
print("Islower Method: ",name.islower())  # Checks if the string is in lowercase
print("Isupper Method: ",name.isupper())  # Checks if the string is in uppercase
print("Isnumeric Method: ",name.isnumeric())  # Checks if the string contains only numeric characters
print("Isspace Method: ",name.isspace())  # Checks if the string contains only whitespace characters
